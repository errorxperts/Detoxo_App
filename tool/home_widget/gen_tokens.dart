// Generates the home-widget token constants for BOTH renderers from the one
// source of truth, `tool/home_widget/tokens.json` (Widget Rules DS-02, DS-10,
// IM-05: "tokens only, never raw hex"; "new tokens go into tokens.json first").
//
//   dart run tool/home_widget/gen_tokens.dart          # (re)write all five files
//   dart run tool/home_widget/gen_tokens.dart --check  # exit 1 on drift (CI)
//
// Outputs:
//   android/app/src/main/kotlin/com/errorxperts/detoxo/widget/WidgetTokens.kt
//   lib/features/content_counter/home_content_counter/presentation/widget_tokens.g.dart
//   lib/features/content_counter/home_content_counter/domain/widget_rules.g.dart
//   android/app/src/main/kotlin/com/errorxperts/detoxo/overlay/bubble/BubbleTokens.kt
//   lib/features/content_counter/content_counter_bubble/presentation/bubble_tokens.g.dart
//
// Tokens named `bubble-*` (the reel bubble, Bubble rules BR-04/05) go to the two
// `BubbleTokens` files with the prefix stripped; everything else is widget-only.
// Kotlin: one object per group (WidgetTokens, BubbleTokens). Dart splits the widget group: the `rule` group
// (colour-free model numbers) goes to the domain's `WidgetRules`, so the
// domain never imports presentation; the rest to the presentation tokens.
//
// Colours are emitted as ARGB ints (Kotlin) / `Color` (Dart) from the SAME
// parsed value, so the native widget and the Flutter preview can never disagree
// on a channel. `rgba(r,g,b,a)` alpha is `round(a * 255)`, half up — CSS's rule.
// The colour parsing, casing, formatting and write/`--check` helpers are shared
// with tool/design/gen_design_tokens.dart in tool/tokens_common.dart.
import 'dart:convert';
import 'dart:io';

import '../tokens_common.dart';

const _tokensPath = 'tool/home_widget/tokens.json';
const _kotlinPath =
    'android/app/src/main/kotlin/com/errorxperts/detoxo/widget/WidgetTokens.kt';
const _dartPath =
    'lib/features/content_counter/home_content_counter/presentation/'
    'widget_tokens.g.dart';
const _rulesPath =
    'lib/features/content_counter/home_content_counter/domain/'
    'widget_rules.g.dart';

const _bubbleKotlinPath =
    'android/app/src/main/kotlin/com/errorxperts/detoxo/overlay/bubble/'
    'BubbleTokens.kt';
const _bubbleDartPath =
    'lib/features/content_counter/content_counter_bubble/presentation/'
    'bubble_tokens.g.dart';

const _header = [
  'GENERATED by tool/home_widget/gen_tokens.dart from tool/home_widget/tokens.json.',
  'Do not edit by hand: change tokens.json, then run',
  '`dart run tool/home_widget/gen_tokens.dart` (Widget Rules DS-02 / IM-05).',
];

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final json =
      jsonDecode(File(_tokensPath).readAsStringSync()) as Map<String, dynamic>;
  final tokens = _Tokens.parse(json);
  final widget = tokens.widget;
  final bubble = tokens.bubble;

  final kotlin = _kotlin(
    widget,
    package: 'com.errorxperts.detoxo.widget',
    object: 'WidgetTokens',
    doc:
        'Home-widget design tokens: colours as ARGB ints, sizes in design units.',
    rename: _same,
  );
  final dart = await formatDart(
    _dart(
      widget,
      object: 'WidgetTokens',
      doc: 'Home-widget design tokens: colours, and sizes in design units.',
      rename: _same,
    ),
  );
  final rules = await formatDart(_rules(widget));
  const bubbleDoc =
      'Reel-bubble design tokens (Bubble rules BR-04/05): colours as ARGB ints, '
      'sizes in dp at size 68.';
  final bubbleKotlin = _kotlin(
    bubble,
    package: 'com.errorxperts.detoxo.overlay.bubble',
    object: 'BubbleTokens',
    doc: bubbleDoc,
    rename: _strip,
  );
  final bubbleDart = await formatDart(
    _dart(
      bubble,
      object: 'BubbleTokens',
      doc:
          'Reel-bubble design tokens (Bubble rules BR-04/05): colours, and sizes in dp at size 68.',
      rename: _strip,
    ),
  );
  syncOutputs(
    [
      (_kotlinPath, kotlin),
      (_dartPath, dart),
      (_rulesPath, rules),
      (_bubbleKotlinPath, bubbleKotlin),
      (_bubbleDartPath, bubbleDart),
    ],
    check: check,
    label: 'home-widget tokens',
    source: _tokensPath,
    regen: 'dart run tool/home_widget/gen_tokens.dart',
  );
}

// ── Model ─────────────────────────────────────────────────────────────────────

class _Colour {
  _Colour(this.name, this.argb, this.usage);
  final String name; // kebab-case, including a -light/-dark suffix for pairs
  final int argb;
  final String usage;
}

class _ColourList {
  _ColourList(this.name, this.items);
  final String name;
  final List<String> items; // colour names (kebab), already suffixed for pairs
}

class _Number {
  _Number(this.name, this.value, this.usage, {required this.isInt});
  final String name;
  final num value;
  final String usage;
  final bool isInt;
}

class _Tokens {
  _Tokens(this.colours, this.lists, this.numbers, this.rules);

  factory _Tokens.parse(Map<String, dynamic> json) {
    final colours = <_Colour>[];
    final pairNames = <String>{};
    for (final raw in json['color'] as List<dynamic>) {
      final t = raw as Map<String, dynamic>;
      final name = t['name'] as String;
      final usage = (t['usage'] as String?) ?? '';
      final value = t['value'];
      if (value is String) {
        colours.add(_Colour(name, parseCssColour(value, name), usage));
      } else if (value is Map<String, dynamic>) {
        pairNames.add(name);
        for (final theme in const ['light', 'dark']) {
          final v = value[theme];
          if (v is! String) throw FormatException('$name: missing $theme');
          colours.add(
            _Colour('$name-$theme', parseCssColour(v, name), '$usage ($theme)'),
          );
        }
      } else {
        throw FormatException('$name: value must be a string or {light,dark}');
      }
    }
    final known = colours.map((c) => c.name).toSet();
    final lists = <_ColourList>[];
    for (final raw in json['colorList'] as List<dynamic>) {
      final l = raw as Map<String, dynamic>;
      final name = l['name'] as String;
      final items = (l['items'] as List<dynamic>).cast<String>();
      final pair = items.every(pairNames.contains);
      if (pair) {
        for (final theme in const ['light', 'dark']) {
          lists.add(
            _ColourList('$name-$theme', [for (final i in items) '$i-$theme']),
          );
        }
      } else {
        for (final i in items) {
          if (!known.contains(i)) throw FormatException('$name: unknown $i');
        }
        lists.add(_ColourList(name, items));
      }
    }
    List<_Number> numbers(String group) => [
      for (final raw in json[group] as List<dynamic>)
        _Number(
          (raw as Map<String, dynamic>)['name'] as String,
          raw['value'] as num,
          (raw['usage'] as String?) ?? '',
          isInt: raw['type'] == 'int',
        ),
    ];
    final rules = numbers('rule');
    for (final r in rules) {
      if (!r.isInt) throw FormatException('${r.name}: a rule must be an int');
    }
    return _Tokens(colours, lists, numbers('number'), rules);
  }

  final List<_Colour> colours;
  final List<_ColourList> lists;
  final List<_Number> numbers;

  /// Colour-free model numbers: Kotlin `WidgetTokens`, Dart `WidgetRules`.
  final List<_Number> rules;

  static bool _isBubble(String name) => name.startsWith('bubble-');

  /// The home-widget tokens: everything not `bubble-*`.
  _Tokens get widget => _view(isBubble: false);

  /// The reel-bubble tokens (rules stay widget-only).
  _Tokens get bubble => _view(isBubble: true);

  _Tokens _view({required bool isBubble}) => _Tokens(
    [
      for (final c in colours)
        if (_isBubble(c.name) == isBubble) c,
    ],
    [
      for (final l in lists)
        if (_isBubble(l.name) == isBubble) l,
    ],
    [
      for (final n in numbers)
        if (_isBubble(n.name) == isBubble) n,
    ],
    isBubble ? const [] : rules,
  );
}

String _numberLiteral(_Number n, {required bool kotlin}) {
  if (n.isInt) return n.value.toInt().toString();
  final v = n.value.toDouble();
  final text = v == v.roundToDouble() ? v.toInt().toString() : v.toString();
  return kotlin ? '${text}f' : text;
}

/// `bubble-glass-from` -> `glass-from`.
String _strip(String name) => name.substring('bubble-'.length);

String _same(String name) => name;

// ── Kotlin ────────────────────────────────────────────────────────────────────

String _kotlin(
  _Tokens t, {
  required String package,
  required String object,
  required String doc,
  required String Function(String) rename,
}) {
  final b = StringBuffer()
    ..writeln(_header.map((l) => '// $l').join('\n'))
    ..writeln('package $package')
    ..writeln()
    ..writeln('/** $doc */')
    ..writeln('@Suppress("unused")')
    ..writeln('internal object $object {');
  for (final c in t.colours) {
    b
      ..writeln('    /** ${c.usage} */')
      ..writeln(
        '    const val ${upperSnake(rename(c.name))}: Int = ${hex8(c.argb)}.toInt()',
      );
  }
  b.writeln();
  for (final l in t.lists) {
    b
      ..writeln('    @JvmField')
      ..writeln(
        '    val ${upperSnake(rename(l.name))}: IntArray = intArrayOf('
        '${l.items.map((i) => upperSnake(rename(i))).join(', ')})',
      );
  }
  b.writeln();
  for (final n in [...t.numbers, ...t.rules]) {
    final type = n.isInt ? 'Int' : 'Float';
    b
      ..writeln('    /** ${n.usage} */')
      ..writeln(
        '    const val ${upperSnake(rename(n.name))}: $type = '
        '${_numberLiteral(n, kotlin: true)}',
      );
  }
  b.writeln('}');
  return b.toString();
}

// ── Dart ──────────────────────────────────────────────────────────────────────

String _dart(
  _Tokens t, {
  required String object,
  required String doc,
  required String Function(String) rename,
}) {
  final b = StringBuffer()
    ..writeln(_header.map((l) => '// $l').join('\n'))
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln('/// $doc')
    ..writeln('abstract final class $object {');
  for (final c in t.colours) {
    b
      ..writeln('  /// ${c.usage}')
      ..writeln(
        '  static const Color ${lowerCamel(rename(c.name))} = Color(${hex8(c.argb)});',
      );
  }
  for (final l in t.lists) {
    b.writeln(
      '  static const List<Color> ${lowerCamel(rename(l.name))} = '
      '[${l.items.map((i) => lowerCamel(rename(i))).join(', ')}];',
    );
  }
  for (final n in t.numbers) {
    final type = n.isInt ? 'int' : 'double';
    b
      ..writeln('  /// ${n.usage}')
      ..writeln(
        '  static const $type ${lowerCamel(rename(n.name))} = '
        '${_numberLiteral(n, kotlin: false)};',
      );
  }
  b.writeln('}');
  return b.toString();
}

String _rules(_Tokens t) {
  final b = StringBuffer()
    ..writeln(_header.map((l) => '// $l').join('\n'))
    ..writeln()
    ..writeln(
      "/// The home widgets' rule numbers, the same values as Kotlin "
      '`WidgetTokens`:',
    )
    ..writeln('/// colour-free, so the domain reads them without presentation.')
    ..writeln('abstract final class WidgetRules {');
  for (final n in t.rules) {
    b
      ..writeln('  /// ${n.usage}')
      ..writeln(
        '  static const int ${lowerCamel(n.name)} = '
        '${_numberLiteral(n, kotlin: false)};',
      );
  }
  b.writeln('}');
  return b.toString();
}
