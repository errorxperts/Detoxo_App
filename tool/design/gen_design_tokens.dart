  String themed(String name, String theme) => upperSnake('$name-$theme');
  final b = StringBuffer()
    ..writeln(_header.map((l) => '// $l').join('\n'))
    ..writeln('package com.errorxperts.detoxo.overlay')
    ..writeln()
    ..writeln('/**')
    ..writeln(' * One CSS box-shadow layer, in CSS order (the first paints on')
    ..writeln(' * top). [blur] is the CSS blur radius: a Gaussian sigma of')
    ..writeln(' * blur / 2.')
    ..writeln(' */')
    ..writeln('internal data class DxShadowLayer(')
    ..writeln('    val color: Int,')
    ..writeln('    val x: Float,')
    ..writeln('    val y: Float,')
    ..writeln('    val blur: Float,')
    ..writeln('    val spread: Float,')
    ..writeln('    val inset: Boolean,')
    ..writeln(')')
    ..writeln()
    ..writeln('''
/**
