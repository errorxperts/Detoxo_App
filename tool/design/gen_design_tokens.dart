  }
  b.writeln();
  for (final s in d.shadows) {
    // Every shadow is SHADOW_*: `shadow-card` → SHADOW_CARD_LIGHT, the
    // recipes' `pill-edge` → SHADOW_PILL_EDGE_LIGHT.
    final name = s.name.startsWith('shadow-') ? s.name : 'shadow-${s.name}';
    for (final theme in _themes) {
      b
        ..writeln('    /** ${s.usage} ($theme) */')
        ..writeln('    @JvmField')
        ..writeln(
          '    val ${themed(name, theme)}: Array<DxShadowLayer> = arrayOf(',
        );
      for (final l in s.value[theme]!) {
        b.writeln('        ${_ktShadow(l)},');
      }
      b.writeln('    )');
    }
  }
  b.writeln();
  for (final s in d.styles) {
    final name = upperSnake(s.name);
    final tracking = s.tracking == 0
        ? '0f'
        : '${_kt(s.tracking)} / ${_kt(s.size)}';
    b
      ..writeln('    /** ${s.usage} */')
      ..writeln('    const val ${name}_SIZE: Float = ${_kt(s.size)}')
      ..writeln('    const val ${name}_LINE: Float = ${_kt(s.line)}')
      ..writeln('    const val ${name}_WEIGHT: Int = ${s.weight}')
      ..writeln('    const val ${name}_TRACKING_EM: Float = $tracking');
  }
  b.writeln();
  for (final s in d.statics) {
    b
      ..writeln('    /** ${s.usage} */')
      ..writeln(
        s.colour != null
            ? '    const val ${upperSnake(s.name)}: Int = '
                  '${_ktColour(s.colour!)}'
            : '    const val ${upperSnake(s.name)}: Float = ${_kt(s.number!)}',
      );
  }
  b.writeln('}');
  return b.toString();
}
