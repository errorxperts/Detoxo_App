// Generates the Frozen Glass design tokens for BOTH renderers (Flutter and the
// native block screen) from one source of truth:
//   tool/design/tokens.json  — a byte copy of the Detoxo Design System spec.
//                              Never edit it, so a spec update is a plain diff.
//   tool/design/recipes.json — the components/bundle.css values tokens.json
//                              lacks, plus documented local overrides.
//
//   dart run tool/design/gen_design_tokens.dart          # (re)write both files
//   dart run tool/design/gen_design_tokens.dart --check  # exit 1 on drift (CI)
//
// Outputs:
//   lib/core/design_system/tokens/app_tokens.g.dart (part of app_tokens.dart)
//   android/app/src/main/kotlin/com/errorxperts/detoxo/overlay/DxTokens.kt
//
// Colours: a {light, dark} value is a themed field, a P-main / P-light / P-deep
// set is an AccentPalette and a fixed `tone-<t>-<f>` is ConfirmTone.<t>.<f>.
// Shadows keep the CSS layer order and the CSS blur RADIUS (a Gaussian sigma of
// blur / 2 at paint time). Type keeps the CSS line box: `height: L / S` with
// even leading. Values with a CSS unit keep it in the JSON: `%` is read as a
// fraction, `px` and `deg` as plain numbers.
import 'dart:convert';
import 'dart:io';

import '../tokens_common.dart';

const _tokensPath = 'tool/design/tokens.json';
const _recipesPath = 'tool/design/recipes.json';
const _dartPath = 'lib/core/design_system/tokens/app_tokens.g.dart';
const _kotlinPath =
    'android/app/src/main/kotlin/com/errorxperts/detoxo/overlay/DxTokens.kt';

const _themes = ['light', 'dark'];
const _stops = ['main', 'light', 'deep'];
const _toneFields = ['a', 'b', 'c', 'ink', 'knob'];

/// Spec palette prefixes split into words: `blockAll`, `BLOCK_ALL_MAIN_LIGHT`.
const _aliases = {'blockall': 'block-all', 'onereel': 'one-reel'};

const _header = [
  'GENERATED by tool/design/gen_design_tokens.dart from tool/design/tokens.json',
  '(a byte copy of the Detoxo Design System spec) and tool/design/recipes.json.',
  'Do not edit by hand: change recipes.json (or re-copy tokens.json), then run',
  '`dart run tool/design/gen_design_tokens.dart`.',
];

Future<void> main(List<String> args) async {
  final d = _Design.parse(_json(_tokensPath), _json(_recipesPath));
  syncOutputs(
    [(_dartPath, await formatDart(_dart(d))), (_kotlinPath, _kotlin(d))],
    check: args.contains('--check'),
    label: 'design tokens',
    source: '$_tokensPath + $_recipesPath',
    regen: 'dart run tool/design/gen_design_tokens.dart',
  );
}

Map<String, dynamic> _json(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

/// The `tokens` of a `{note, tokens}` group.
List<Map<String, dynamic>> _group(Map<String, dynamic> json, String group) => [
  for (final t
      in (json[group] as Map<String, dynamic>)['tokens'] as List<dynamic>)
    t as Map<String, dynamic>,
];

String _usage(Map<String, dynamic> token) => token['usage'] as String? ?? '';

// ── Model ─────────────────────────────────────────────────────────────────────

/// One value per theme, keyed by [_themes].
class _Themed<T> {
  _Themed(this.name, this.usage, this.value, {this.overrides = const {}});

  final String name; // kebab-case
  final String usage;
  final Map<String, T> value;

  /// Theme → why tool/design/recipes.json replaced the spec value there.
  final Map<String, String> overrides;

  _Themed<R> map<R>(R Function(T) f) => _Themed(name, usage, {
    for (final MapEntry(:key, :value) in value.entries) key: f(value),
  }, overrides: overrides);
}

/// One CSS box-shadow layer; [blur] is the CSS blur radius.
class _Layer {
  _Layer(
    this.colour,
    this.x,
    this.y,
    this.blur,
    this.spread, {
    required this.inset,
  });

  final int colour;
  final double x;
  final double y;
  final double blur;
  final double spread;
  final bool inset;

  /// This layer with its alpha times [k].
  _Layer fade(double k) => _Layer(
    ((colour >>> 24) * k).round() << 24 | colour & 0xFFFFFF,
    x,
    y,
    blur,
    spread,
    inset: inset,
  );
}

class _Style {
  _Style(
    this.name,
    this.usage, {
    required this.size,
    required this.line,
    required this.weight,
    required this.tracking,
  });

  final String name;
  final String usage;
  final double size;
  final double line;
  final int weight;
  final double tracking;
}

/// A theme-independent colour (`#…` / `rgba(…)`) or number.
class _Static {
  _Static(this.name, this.usage, String css)
    : colour = _isColour(css) ? parseCssColour(css, name) : null,
      number = _isColour(css) ? null : _cssNumber(css, name);

  final String name;
  final String usage;
  final int? colour;
  final double? number;

  static bool _isColour(String css) =>
      css.startsWith('#') || css.startsWith('rgba(');
}

typedef _Tone = ({String name, String usage, Map<String, int> stops});

class _Design {
  _Design({
    required this.colours,
    required this.palettes,
    required this.tones,
    required this.strengths,
    required this.shadows,
    required this.family,
    required this.styles,
    required this.statics,
  });

  factory _Design.parse(
    Map<String, dynamic> spec,
    Map<String, dynamic> recipes,
  ) {
    final colours = <_Themed<int>>[];
    final tones = <String, _Tone>{};
    final statics = <_Static>[];
    for (final c in [..._group(spec, 'color'), ..._group(recipes, 'color')]) {
      final name = _alias(c['name'] as String);
      final tone = _tone.firstMatch(name);
      switch (c['value']) {
        case final String v when tone != null:
          final toneName = tone.group(1)!;
          // The first stop's usage minus its stop phrase: "Critical tone
          // (…): fill start." → "Critical tone (…)."
          final t = tones.putIfAbsent(
            toneName,
            () => (
              name: toneName,
              usage: _usage(c).replaceFirst(RegExp(r':[^:]*$'), '.'),
              stops: {},
            ),
          );
          t.stops[tone.group(2)!] = parseCssColour(v, name);
        case final String v:
          statics.add(_Static(name, _usage(c), v));
        case final v:
          colours.add(
            _Themed(name, _usage(c), _perTheme(v, name, parseCssColour)),
          );
      }
    }
    for (final t in tones.values) {
      if (t.stops.length != _toneFields.length ||
          !_toneFields.every(t.stops.containsKey)) {
        throw FormatException('tone-${t.name}: needs exactly $_toneFields');
      }
    }

    for (final o in _group(recipes, 'override')) {
      final name = _alias(o['name'] as String);
      final i = colours.indexWhere((c) => c.name == name);
      final patch = o['value'] as Map<String, dynamic>;
      if (i < 0 || !patch.keys.every(_themes.contains)) {
        throw FormatException('override $name: no such themed colour/theme');
      }
      final c = colours[i];
      colours[i] = _Themed(
        c.name,
        c.usage,
        {
          ...c.value,
          for (final MapEntry(:key, :value) in patch.entries)
            key: parseCssColour(value as String, name),
        },
        overrides: {for (final theme in patch.keys) theme: _usage(o)},
      );
    }

    final byName = {for (final c in colours) c.name: c};
    final palettes = <_Themed<List<int>>>[];
    for (final main in colours.where((c) => c.name.endsWith('-main'))) {
      final p = main.name.substring(0, main.name.length - '-main'.length);
      final stops = [for (final s in _stops) byName['$p-$s']].nonNulls.toList();
      if (stops.length != _stops.length) continue;
      palettes.add(
        _Themed(p, main.usage, {
          for (final theme in _themes)
            theme: [for (final s in stops) s.value[theme]!],
        }),
      );
    }

    // recipes.json `shadowScale`: soft (blurred) layers at a share of their
    // spec alpha; rim lines and the `except` tokens keep it.
    final scale = recipes['shadowScale'] as Map<String, dynamic>;
    final k = _cssNumber(scale['value'] as String, 'shadowScale');
    final except = (scale['except'] as List<dynamic>).toSet();
    final shadows = [
      for (final s in [..._group(spec, 'shadow'), ..._group(recipes, 'shadow')])
        except.contains(s['name'])
            ? _shadowToken(s)
            : _shadowToken(s).map(
                (layers) => [
                  for (final l in layers) l.blur > 0 ? l.fade(k) : l,
                ],
              ),
    ];

    final type = spec['type'] as Map<String, dynamic>;
    final families = type['families'] as Map<String, dynamic>;
    final familyNames = <String>{};
    final styles = <_Style>[];
    for (final raw in type['groups'] as List<dynamic>) {
      final group = raw as Map<String, dynamic>;
      // `Manrope, "SF Pro Rounded", …` → Manrope; the rest are web fallbacks.
      familyNames.add(
        (families[group['family']] as String)
            .split(',')
            .first
            .replaceAll('"', '')
            .trim(),
      );
      for (final s in group['styles'] as List<dynamic>) {
        final style = s as Map<String, dynamic>;
        final name = style['name'] as String;
        styles.add(
          _Style(
            name,
            _usage(style),
            size: _cssNumber(style['fontSize'] as String, name),
            line: _cssNumber(style['lineHeight'] as String, name),
            weight: style['fontWeight'] as int,
            tracking: _cssNumber(
              style['letterSpacing'] as String? ?? '0',
              name,
            ),
          ),
        );
      }
    }
    if (familyNames.length != 1) {
      throw FormatException('type: one family expected, got $familyNames');
    }
    for (final v in _group(recipes, 'typeVariant')) {
      final name = v['name'] as String;
      final i = styles.indexWhere((s) => s.name == v['base']);
      if (i < 0) throw FormatException('$name: no base style ${v['base']}');
      final base = styles[i];
      // A variant overrides only the fields it names; the rest are the base's.
      double? css(String key) => switch (v[key]) {
        final String s => _cssNumber(s, name),
        _ => null,
      };
      styles.insert(
        i + 1,
        _Style(
          name,
          _usage(v),
          size: css('fontSize') ?? base.size,
          line: css('lineHeight') ?? base.line,
          weight: v['fontWeight'] as int? ?? base.weight,
          tracking: css('letterSpacing') ?? base.tracking,
        ),
      );
    }

    for (final group in [
      _group(spec, 'spacing'),
      _group(spec, 'radius'),
      _group(recipes, 'surface'),
      _group(recipes, 'fixed'),
    ]) {
      for (final s in group) {
        statics.add(
          _Static(s['name'] as String, _usage(s), s['value'] as String),
        );
      }
    }

    return _Design(
      colours: colours,
      palettes: palettes,
      tones: tones.values.toList(),
      strengths: [
        for (final k in _group(recipes, 'strength'))
          _Themed(
            k['name'] as String,
            _usage(k),
            _perTheme(k['value'], k['name'] as String, _cssNumber),
          ),
      ],
      shadows: shadows,
      family: familyNames.single,
      styles: styles,
      statics: statics,
    );
  }

  /// Every themed colour, palette stops included (Kotlin's flat ints).
  final List<_Themed<int>> colours;
  final List<_Themed<List<int>>> palettes; // main, light, deep per theme
  final List<_Tone> tones;
  final List<_Themed<double>> strengths;
  final List<_Themed<List<_Layer>>> shadows;
  final String family;
  final List<_Style> styles;
  final List<_Static> statics;

  /// Themed colours that are not palette stops: Dart's `Color` fields.
  Iterable<_Themed<int>> get plainColours {
    final stops = {
      for (final p in palettes)
        for (final s in _stops) '${p.name}-$s',
    };
    return colours.where((c) => !stops.contains(c.name));
  }
}

final _tone = RegExp(r'^tone-([a-z]+)-([a-z]+)$');

String _alias(String name) {
  for (final MapEntry(:key, :value) in _aliases.entries) {
    if (name.startsWith('$key-')) return value + name.substring(key.length);
  }
  return name;
}

Map<String, T> _perTheme<T>(
  Object? value,
  String name,
  T Function(String v, String name) parse,
) {
  if (value is! Map<String, dynamic>) {
    throw FormatException('$name: value must be a string or {light,dark}');
  }
  return {
    for (final theme in _themes)
      theme: switch (value[theme]) {
        final String v => parse(v, name),
        _ => throw FormatException('$name: missing $theme'),
      },
  };
}

final _number = RegExp(r'^(-?(?:\d+|\d*\.\d+))(px|%|deg)?$');

/// `8px` → 8, `14%` → 0.14, `214deg` → 214, `.7` → 0.7.
double _cssNumber(String v, String name) {
  final m =
      _number.firstMatch(v) ??
      (throw FormatException('$name: unsupported number "$v"'));
  final n = double.parse(m.group(1)!);
  return m.group(2) == '%' ? n / 100 : n;
}

/// A CSS box-shadow list: layers split on top-level commas, each an optional
/// `inset`, one colour and 2–4 lengths (x, y, blur, spread). Light and dark
/// must have the same layer shapes, so a painter can treat them alike.
_Themed<List<_Layer>> _shadowToken(Map<String, dynamic> token) {
  final name = token['name'] as String;
  final shadow = _Themed(
    name,
    _usage(token),
    _perTheme(token['value'], name, _shadow),
  );
  final [light, dark] = [for (final theme in _themes) shadow.value[theme]!];
  if (light.length != dark.length ||
      Iterable<int>.generate(
        light.length,
      ).any((i) => light[i].inset != dark[i].inset)) {
    throw FormatException('$name: light and dark layers differ in shape');
  }
  return shadow;
}

final _colourIn = RegExp(r'#[0-9a-fA-F]{6}|rgba\([^)]*\)');

List<_Layer> _shadow(String css, String name) => [
  for (final layer in css.split(RegExp(r',(?![^(]*\))')))
    _layer(layer.trim(), name),
];

_Layer _layer(String css, String name) {
  final colour =
      _colourIn.firstMatch(css) ??
      (throw FormatException('$name: no colour in "$css"'));
  final words = css
      .replaceRange(colour.start, colour.end, ' ')
      .trim()
      .split(RegExp(r'\s+'));
  final inset = words.remove('inset');
  final lengths = [
    for (final w in words)
      w == '0' || w.endsWith('px')
          ? _cssNumber(w, name)
          : throw FormatException('$name: "$w" is not a length'),
  ];
  if (lengths.length < 2 || lengths.length > 4) {
    throw FormatException('$name: "$css" needs 2-4 lengths');
  }
  return _Layer(
    parseCssColour(colour.group(0)!, name),
    lengths[0],
    lengths[1],
    lengths.elementAtOrNull(2) ?? 0,
    lengths.elementAtOrNull(3) ?? 0,
    inset: inset,
  );
}

/// `8` for whole numbers, else the shortest round-trip form (`0.06`).
String _num(double v) =>
    v == v.roundToDouble() ? v.toInt().toString() : v.toString();

// ── Dart ──────────────────────────────────────────────────────────────────────

String _dartColour(int argb) => 'Color(${hex8(argb)})';

/// A `DxShadow(...)` literal that leaves out the constructor defaults.
String _dartShadow(_Layer l) {
  final args = [
    'color: ${_dartColour(l.colour)}',
    if (l.x != 0 || l.y != 0) 'offset: Offset(${_num(l.x)}, ${_num(l.y)})',
    if (l.blur != 0) 'blur: ${_num(l.blur)}',
    if (l.spread != 0) 'spread: ${_num(l.spread)}',
    if (l.inset) 'inset: true',
  ];
  return 'DxShadow(${args.join(', ')})';
}

String _dartStyle(_Style s) =>
    '''
TextStyle(
  fontFamily: family,
  fontSize: ${_num(s.size)},
  height: ${_num(s.line)} / ${_num(s.size)},
  fontWeight: FontWeight.w${s.weight},
  letterSpacing: ${_num(s.tracking)},
  leadingDistribution: TextLeadingDistribution.even,
  fontFeatures: [FontFeature.tabularFigures()],
)''';

void _docs(StringBuffer b, String usage, {String override = ''}) {
  b.writeln('  /// $usage');
  if (override.isNotEmpty) {
    b
      ..writeln('  ///')
      ..writeln('  /// Override (tool/design/recipes.json): $override');
  }
}

String _dart(_Design d) {
  // (Dart type, per-theme literal) for every instance field.
  final fields = <(String, _Themed<String>)>[
    for (final c in d.plainColours) ('Color', c.map(_dartColour)),
    for (final p in d.palettes)
      (
        'AccentPalette',
        p.map((s) => 'AccentPalette(${s.map(_dartColour).join(', ')})'),
      ),
    for (final k in d.strengths) ('double', k.map(_num)),
    for (final s in d.shadows)
      ('List<DxShadow>', s.map((l) => '[${l.map(_dartShadow).join(', ')}]')),
  ];
  final b = StringBuffer()
    ..writeln(_header.map((l) => '// $l').join('\n'))
    ..writeln('''
part of 'app_tokens.dart';

/// The Frozen Glass tokens of one theme ([light] or [dark]) plus the
/// theme-independent statics. Read them through `context.tokens`.
final class AppTokens {
  const AppTokens._({
    required this.brightness,''');
  for (final (_, f) in fields) {
    b.writeln('    required this.${lowerCamel(f.name)},');
  }
  b.writeln('  });');
  for (final theme in _themes) {
    b
      ..writeln()
      ..writeln('  static const AppTokens $theme = AppTokens._(')
      ..writeln('    brightness: Brightness.$theme,');
    for (final (_, f) in fields) {
      b.writeln('    ${lowerCamel(f.name)}: ${f.value[theme]},');
    }
    b.writeln('  );');
  }
  b
    ..writeln()
    ..writeln('  /// [light] or [dark] for a theme brightness.')
    ..writeln('  static AppTokens forBrightness(Brightness b) =>')
    ..writeln('      b == Brightness.dark ? dark : light;')
    ..writeln()
    ..writeln('  final Brightness brightness;');
  for (final (type, f) in fields) {
    b.writeln();
    _docs(b, f.usage, override: f.overrides.values.toSet().join(' '));
    b.writeln('  final $type ${lowerCamel(f.name)};');
  }
  b
    ..writeln()
    ..writeln('  /// Every accent palette, in spec order.')
    ..writeln(
      '  List<AccentPalette> get palettes => '
      '[${d.palettes.map((p) => lowerCamel(p.name)).join(', ')}];',
    );
  for (final s in d.statics) {
    b.writeln();
    _docs(b, s.usage);
    b.writeln(
      s.colour != null
          ? '  static const Color ${lowerCamel(s.name)} = '
                '${_dartColour(s.colour!)};'
          : '  static const double ${lowerCamel(s.name)} = '
                '${_num(s.number!)};',
    );
  }
  b.writeln('''
}

/// The confirm sheet's tones: the slide fill [a] → [b] (at 55 %) → [c], the
/// text on it ([ink]) and the glyphs on the knob ([knob]).
enum ConfirmTone {''');
  for (final (i, t) in d.tones.indexed) {
    final stops = _toneFields
        .map((f) => '$f: ${_dartColour(t.stops[f]!)}')
        .join(', ');
    b
      ..writeln('  /// ${t.usage}')
      ..writeln(
        '  ${lowerCamel(t.name)}($stops)${i == d.tones.length - 1 ? ';' : ','}',
      );
  }
  b
    ..writeln()
    ..writeln(
      '  const ConfirmTone({'
      '${_toneFields.map((f) => 'required this.$f').join(', ')}});',
    )
    ..writeln();
  for (final f in _toneFields) {
    b.writeln('  final Color $f;');
  }
  b.writeln('''
}

/// The spec's named text styles: ${d.family}, tabular figures and even (CSS)
/// leading, with `height` = line height / font size.
abstract final class AppTypography {
  /// The first family of the spec's sans stack.
  static const String family = '${d.family}';''');
  for (final s in d.styles) {
    b.writeln();
    _docs(b, s.usage);
    b.writeln(
      '  static const TextStyle ${lowerCamel(s.name)} = ${_dartStyle(s)};',
    );
  }
  b.writeln('}');
  return b.toString();
}

// ── Kotlin ────────────────────────────────────────────────────────────────────

String _kt(double v) => '${_num(v)}f';

String _ktColour(int argb) => '${hex8(argb)}.toInt()';

String _ktShadow(_Layer l) =>
    'DxShadowLayer(${_ktColour(l.colour)}, ${_kt(l.x)}, ${_kt(l.y)}, '
    '${_kt(l.blur)}, ${_kt(l.spread)}, ${l.inset})';

